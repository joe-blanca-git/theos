// Calcular tempo de leitura estimado (baseado em ~200 palavras por minuto)
function getReadingTime(text) {
  const words = text.replace(/<[^>]*>?/gm, '').split(/\s+/).length;
  const minutes = Math.ceil(words / 200);
  return minutes > 0 ? minutes : 1;
}

// Utilitário para formatar a data
function formatDate(dateString) {
  const options = { day: 'numeric', month: 'long', year: 'numeric' };
  return new Date(dateString).toLocaleDateString('pt-BR', options);
}

// Utilitário para transformar tags string em array limpo
function parseTags(tagsString) {
  if (!tagsString) return [];
  return tagsString.split(',').map(tag => tag.trim()).filter(t => t);
}
